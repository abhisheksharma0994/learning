"""A simulated model that is skilful but systematically overconfident.

Used by the tests and the demo report. It exists so the calibration layer can be
exercised -- and shown to help -- without a GPU, a download, or an API key.

The simulation has three knobs, which mirror the real failure modes:

* ``accuracy``     -- how often the argmax is actually right. The latent margin
  is solved so that the *realized* accuracy matches this, including the effect of
  the per-example difficulty jitter.
* ``overconfidence`` -- a power sharpening of the distribution. It inflates the
  stated confidence without changing which label wins, so temperature scaling
  can largely undo it.
* ``winner_bias``  -- an additive bonus on the winning logit, in latent units,
  applied before sharpening. It is not a temperature effect, so it survives
  temperature scaling. That residual is what a non-parametric calibrator earns
  its keep on.

``margin_jitter`` varies difficulty across examples, which is what makes a
risk-coverage curve interesting: some cases are genuinely easier than others.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass, field

from .._mathx import softmax
from ..metrics import argmax
from ..scorer import LabelSet

__all__ = ["SyntheticDecisionTask", "SyntheticScorer"]


@dataclass
class SyntheticDecisionTask:
    """Generates labelled decision cases and the model that scores them."""

    n_labels: int = 32
    accuracy: float = 0.72
    overconfidence: float = 8.0
    winner_bias: float = 0.40
    margin_jitter: float = 0.45
    seed: int = 0
    prefix: str = "case"

    label_set: LabelSet = field(init=False)
    truth: dict[str, int] = field(default_factory=dict, init=False)

    def __post_init__(self) -> None:
        if self.n_labels < 2:
            raise ValueError("n_labels must be >= 2")
        if not 0.0 < self.accuracy < 1.0:
            raise ValueError("accuracy must be in (0, 1)")
        if self.overconfidence <= 0:
            raise ValueError("overconfidence must be positive")
        if self.margin_jitter < 0:
            raise ValueError("margin_jitter must be non-negative")
        self.label_set = LabelSet(tuple(f"page-{i:02d}" for i in range(self.n_labels)))

    def sample(self, n: int, seed: int | None = None) -> tuple[list[str], list[int]]:
        """Create ``n`` new cases. Returns ``(states, true_label_indices)``."""
        if n < 1:
            raise ValueError("n must be >= 1")
        rng = random.Random(self.seed if seed is None else seed)
        states: list[str] = []
        targets: list[int] = []
        for _ in range(n):
            state = f"{self.prefix}-{rng.randrange(10**12):012d}"
            target = rng.randrange(self.n_labels)
            self.truth[state] = target
            states.append(state)
            targets.append(target)
        return states, targets

    def scorer(self) -> "SyntheticScorer":
        """The (deliberately overconfident) model for this task."""
        return SyntheticScorer(self)


class SyntheticScorer:
    """Scores states generated by a :class:`SyntheticDecisionTask`."""

    #: Probe cases used to solve the latent margin. More probes means the
    #: realized accuracy lands closer to the requested one; the Monte Carlo
    #: standard error here is about 0.005.
    PROBES = 8192

    def __init__(self, task: SyntheticDecisionTask) -> None:
        self.task = task
        self.label_set = task.label_set
        self.forward_passes = 0

        # A simulated population of decision cases: the true label's own logit,
        # the best competing logit, and a difficulty multiplier. Drawing the
        # competitor as the max of (n_labels - 1) independent normals is exactly
        # the process ``_latent_logits`` follows, so the accuracy solved here is
        # the accuracy that shows up in practice. Sampling these once keeps the
        # solver deterministic across runs.
        probe_rng = random.Random(f"{task.seed}:probes")
        n_competitors = len(self.label_set) - 1
        jitter = task.margin_jitter
        self._probe_truth: list[float] = []
        self._probe_best: list[float] = []
        self._probe_multiplier: list[float] = []
        for _ in range(self.PROBES):
            self._probe_truth.append(probe_rng.gauss(0.0, 1.0))
            self._probe_best.append(
                max(probe_rng.gauss(0.0, 1.0) for _ in range(n_competitors))
            )
            # Mean-corrected lognormal jitter: without the -sigma^2/2 term the
            # jitter would push realized accuracy above the requested value.
            self._probe_multiplier.append(
                math.exp(probe_rng.gauss(0.0, jitter) - 0.5 * jitter * jitter)
            )

        self._margin = self._solve_margin()

    @property
    def honest_margin(self) -> float:
        """The latent true-label margin that reproduces the target accuracy."""
        return self._margin

    def _estimated_accuracy(self, margin: float) -> float:
        wins = sum(
            1
            for truth, best, multiplier in zip(
                self._probe_truth, self._probe_best, self._probe_multiplier
            )
            if truth + margin * multiplier > best
        )
        return wins / self.PROBES

    def _solve_margin(self) -> float:
        """Bisect the latent margin that yields the requested accuracy.

        Accuracy is monotone in the margin, so bisection is exact up to the
        Monte Carlo resolution of the probe set.
        """
        lo, hi = 0.0, 14.0
        if self._estimated_accuracy(hi) < self.task.accuracy:
            return hi
        for _ in range(40):
            mid = (lo + hi) / 2.0
            if self._estimated_accuracy(mid) < self.task.accuracy:
                lo = mid
            else:
                hi = mid
        return (lo + hi) / 2.0

    def _latent_logits(self, state: str) -> list[float]:
        if state not in self.task.truth:
            raise KeyError(
                f"state {state!r} was not produced by this task; call task.sample() first"
            )
        target = self.task.truth[state]
        rng = random.Random(f"{self.task.seed}:{state}")
        logits = [rng.gauss(0.0, 1.0) for _ in range(len(self.label_set))]
        jitter = self.task.margin_jitter
        margin = self._margin * math.exp(rng.gauss(0.0, jitter) - 0.5 * jitter * jitter)
        logits[target] += margin
        return logits

    def score_logits(self, states: list[str]) -> list[list[float]]:
        """Pre-softmax scores, for calibrators that want to fit on logits."""
        self.forward_passes += 1
        return [self._latent_logits(state) for state in states]

    def score(self, states: list[str]) -> list[list[float]]:
        """Overconfident probabilities: biased toward the winner, then sharpened."""
        self.forward_passes += 1
        gamma = self.task.overconfidence
        out: list[list[float]] = []
        for state in states:
            logits = self._latent_logits(state)
            # A bias on the winner cannot flip the argmax, so accuracy is
            # untouched -- it only inflates stated confidence, and it does so in
            # a way that no temperature can undo.
            logits[argmax(logits)] += self.task.winner_bias
            out.append(softmax([gamma * value for value in logits]))
        return out
